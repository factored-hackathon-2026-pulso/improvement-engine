#!/usr/bin/env python3
"""Regenerates src/generated.rs from bridge-contract/contract.json and core-bridge ADR 0012.

Usage (repo root): python seams/crates/core-client/gen/gen_tables.py
`tests/pins.rs` and `tests/classifier.rs` fail when src/generated.rs drifts from the sources.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[4]
C = json.loads((ROOT / "bridge-contract/contract.json").read_text(encoding="utf-8"))
ADR = (ROOT / "core-bridge/docs/adr/0012-agent-core-pin-c814c2b.md").read_text(encoding="utf-8")
DIGEST = re.search(r"MANIFEST digest: `([0-9a-f]{64})`", ADR).group(1)


def kind(code, statuses):
    if code.startswith("pulso:auth_"):
        return "Auth"
    s = statuses[0]
    return {400: "Invalid", 413: "Invalid", 422: "Invalid", 404: "NotFound", 409: "Conflict", 429: "Capacity",
            503: "Unavailable", 500: "Internal", 501: "Internal", 405: "Invalid", 403: "Denied", 200: "Progress"}[s]


out = ["// @generated by gen/gen_tables.py from bridge-contract/contract.json + core-bridge ADR 0012. Do not edit.",
       "use crate::errors::{Disposition, ErrorKind, Kind};", ""]
out.append(f'pub const AGENT_CORE_SHA: &str = "{C["pin"]["agent_core_sha"]}";')
out.append(f'pub const CONTRACTS_VERSION: &str = "{C["pin"]["contracts_version"]}";')
out.append(f'pub const MANIFEST_SHA256: &str = "{DIGEST}";')
out.append(f'pub const BASE_PATH: &str = "{C["base_path"]}";')
out.append(f'pub const CONTRACT_REVISION: &str = "{C["contract_revision"]}";')
out.append(f'pub const JWT_ISS: &str = "{C["auth"]["token"]["iss"]}";')
out.append(f'pub const JWT_AUD: &str = "{C["auth"]["token"]["aud"]}";')
out.append(f'pub const JWT_MAX_TTL_SECONDS: i64 = {C["auth"]["token"]["max_ttl_seconds"]};')
out.append("")
out.append("pub const TABLE: &[ErrorKind] = &[")
for code, spec in sorted(C["error_codes"]["wire"].items()):
    d = "Retry" if spec["retryable"] else "Terminal"
    st = ", ".join(str(s) for s in spec["status"])
    out.append(f'    ErrorKind {{ code: "{code}", kind: Kind::{kind(code, spec["status"])}, retryable: {str(spec["retryable"]).lower()}, '
               f'disposition: Disposition::{d}, statuses: &[{st}] }},')
out.append("];")
out.append("")
out.append("pub const AUTH_REASONS: &[(&str, u16)] = &[")
rs = C["auth"]["reason_status"]
for r in C["auth"]["reasons"]:
    out.append(f'    ("{r}", {rs.get(r, rs["*"])}),')
out.append("];")
(ROOT / "seams/crates/core-client/src/generated.rs").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
